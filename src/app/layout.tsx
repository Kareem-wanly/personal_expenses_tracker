import type { Metadata, Viewport } from "next";
import { Noto_Kufi_Arabic, Reem_Kufi } from "next/font/google";

import { Providers } from "@/components/providers";
import {
  SPLASH_ANIMATION_CSS,
  SPLASH_CSS,
  SPLASH_SCRIPT,
  STARTUP_DEVICES,
  splashInnerHtml,
  startupImageMedia,
  startupImagePath,
} from "@/lib/brand";
import { APP_DESCRIPTION, APP_NAME } from "@/lib/constants";
import "./globals.css";

/** Body text: a Kufi workhorse that stays readable at small sizes. */
const font = Noto_Kufi_Arabic({
  variable: "--font-body",
  subsets: ["arabic", "latin"],
  weight: "variable",
  display: "swap",
});

/** Display: geometric Kufi for headings and every big figure (see globals.css). */
const display = Reem_Kufi({
  variable: "--font-display",
  subsets: ["arabic", "latin"],
  weight: "variable",
  display: "swap",
});

export const metadata: Metadata = {
  applicationName: APP_NAME,
  title: { default: APP_NAME, template: `%s · ${APP_NAME}` },
  description: APP_DESCRIPTION,
  appleWebApp: {
    capable: true,
    statusBarStyle: "default",
    title: APP_NAME,
    // Launch screen iOS shows while the installed app starts (one per
    // screen size; generated by `npm run brand`).
    startupImage: STARTUP_DEVICES.map((d) => ({
      url: startupImagePath(d),
      media: startupImageMedia(d),
    })),
  },
  formatDetection: { telephone: false },
  icons: {
    icon: [
      { url: "/icons/icon.svg", type: "image/svg+xml" },
      { url: "/icons/icon-192.png", sizes: "192x192", type: "image/png" },
    ],
    apple: "/icons/apple-touch-icon.png",
  },
};

export const viewport: Viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#f3f0e8" },
    { media: "(prefers-color-scheme: dark)", color: "#12110e" },
  ],
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="ar"
      dir="rtl"
      className={`${font.variable} ${display.variable} h-full`}
      suppressHydrationWarning
    >
      <head>
        {/* Before first paint: show the launch animation once per session. */}
        <script dangerouslySetInnerHTML={{ __html: SPLASH_SCRIPT }} />
        <style dangerouslySetInnerHTML={{ __html: SPLASH_CSS + SPLASH_ANIMATION_CSS }} />
      </head>
      <body className="flex min-h-full flex-col">
        {/*
          Continues iOS's static launch image (same markup, see lib/brand),
          then opens into the app. Installed app only; CSS-driven, so it
          plays before JavaScript loads and never blocks the page.
        */}
        <div
          className="splash"
          aria-hidden
          style={{ "--splash-font": "var(--font-display)" } as React.CSSProperties}
          dangerouslySetInnerHTML={{ __html: splashInnerHtml() }}
        />
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
